  /** \brief Get the rootfinder input scheme

      Returns the names of the 2 inputs of a Function created by rootfinder from a
      dictionary, in order: x0, p. A Function created from a general Function keeps that
      Function's input names, with "0" appended to the unknown.

      \lang{python}
      \doctest
      >>> rootfinder_in()
      ['x0', 'p']
      \enddoctest
      \endlang

      \lang{matlab}
      \doctest
      >> rootfinder_in()
      x0
      p
      \enddoctest
      \endlang

      \lang{julia}
      \doctest
      julia> ca.rootfinder_in()
      2-element Vector{String}:
       "x0"
       "p"
      \enddoctest
      \endlang

      \sa rootfinder_out, rootfinder_n_in

      \identifier{1ty} */
